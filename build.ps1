# Build wrapper: activates TuyaOpen and layers sdkconfig.overlay over the
# platform defaults (ESP-IDF honours the SDKCONFIG_DEFAULTS env var).
#   .\build.ps1                build
#   .\build.ps1 clean          full clean (after changing Kconfig/overlay/app_default.config)
#   .\build.ps1 flash [COM5]   build + flash (auto reset into the bootloader)
#   .\build.ps1 flash-manual   flash a board already put into the bootloader by hand
#                              (hold BOOT, tap RESET, release BOOT); press RESET after
#   .\build.ps1 log [seconds]  show the device log (no chip reset)
#   .\build.ps1 ota [IP]       build + update over Wi-Fi (LAN OTA, port 8080); without
#                              an IP the board is searched for on the local /24 network
#   .\build.ps1 cmd "status"   run a console command on the board over Wi-Fi, show the new log
#   .\build.ps1 rlog           the board log over Wi-Fi
#   .\build.ps1 webpass        web UI address and login (http://<board>:8080/, user admin)
param([string]$Action = "build", [string]$Port = "COM5", [int]$Seconds = 20)

# No "Stop" here: PowerShell 5.1 turns native stderr (tos.py logs) into errors.
$Sdk = if ($env:OPEN_SDK_ROOT) { $env:OPEN_SDK_ROOT } else { "$HOME\TuyaOpen" }
$Project = $PSScriptRoot
$IdfPython = Join-Path $Sdk "platform\ESP32\.espressif\python_env\idf5.4_py3.12_env\Scripts\python.exe"
$IdfBuild = Join-Path $Sdk "platform\ESP32\tuya_open_sdk\build"

if (-not $env:VIRTUAL_ENV) {
    Push-Location $Sdk
    . .\export.ps1 *> $null
    Pop-Location
}

$PlatformDefaults = Join-Path $Sdk "platform\ESP32\tuya_open_sdk\sdkconfig.defaults"
$env:SDKCONFIG_DEFAULTS = "$PlatformDefaults;$(Join-Path $Project 'sdkconfig.overlay')" -replace '\\', '/'

# tos.py flash (tyutool) drops the native USB-Serial/JTAG link mid-write on this
# board; esptool from the IDF env with compressed flash_args is reliable once it
# has connected. Connecting is the flaky part on Windows: reset the chip through
# devlog.py first (clean DTR/RTS state), then retry a few times.
function Invoke-Esptool([string]$Before, [string]$After) {
    Push-Location $IdfBuild
    $out = & $IdfPython -m esptool --chip esp32s3 -p $Port --before $Before --after $After write_flash "@flash_args" 2>&1 |
        ForEach-Object { "$_" }
    Pop-Location
    $ok = ($out | Select-String "Hash of data verified").Count -eq 4
    if (-not $ok) { $out | Select-Object -Last 3 | Write-Host }
    return $ok
}

function Invoke-Flash {
    for ($i = 1; $i -le 3; $i++) {
        & $IdfPython (Join-Path $Project "tools\devlog.py") -p $Port -t 1 --reset | Out-Null
        Start-Sleep -Seconds 2
        if (Invoke-Esptool "default_reset" "hard_reset") {
            Write-Host "flash OK"
            return 0
        }
        Write-Host "flash attempt $i failed"
    }
    Write-Host "Could not enter the bootloader automatically. Hold BOOT, tap RESET, release BOOT,"
    Write-Host "then run: .\build.ps1 flash-manual   (and press RESET when it is done)"
    return 1
}

# LAN OTA token: generated once, compiled into the firmware, never committed.
$SecretHeader = Join-Path $Project "include\ota_secret.h"
if (-not (Test-Path $SecretHeader)) {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $tok = -join ($bytes | ForEach-Object { $_.ToString("x2") })
    Set-Content -Path $SecretHeader -Encoding ascii -Value @(
        "/* LAN OTA token - generated by build.ps1, keep out of git */",
        "#define OTA_TOKEN `"$tok`"")
}
# Web UI password (browser login admin:<password>): added to an existing
# header too, so boards updated from older builds get one.
if (-not (Select-String -Path $SecretHeader -Pattern 'WEB_PASSWORD' -Quiet)) {
    $alphabet = "abcdefghjkmnpqrstuvwxyz23456789"
    $bytes = New-Object byte[] 10
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $pw = -join ($bytes | ForEach-Object { $alphabet[$_ % $alphabet.Length] })
    Add-Content -Path $SecretHeader -Encoding ascii -Value "#define WEB_PASSWORD `"$pw`""
}
function Get-OtaToken {
    (Select-String -Path $SecretHeader -Pattern 'OTA_TOKEN "([0-9a-f]+)"').Matches[0].Groups[1].Value
}
function Get-WebPassword {
    (Select-String -Path $SecretHeader -Pattern 'WEB_PASSWORD "([0-9a-z]+)"').Matches[0].Groups[1].Value
}

function Find-Board {
    # the interface with the default gateway, not a VPN/tunnel adapter
    $cfg = Get-NetIPConfiguration | Where-Object { $_.IPv4DefaultGateway -and $_.NetAdapter.Status -eq "Up" } |
        Select-Object -First 1
    $me  = $cfg.IPv4Address | Select-Object -First 1
    if (-not $me) { return $null }
    $prefix = ($me.IPAddress -split '\.')[0..2] -join '.'
    Write-Host "searching $prefix.0/24 for the board (port 8080)..."
    $conns = 1..254 | ForEach-Object {
        $c = New-Object System.Net.Sockets.TcpClient
        @{ ip = "$prefix.$_"; c = $c; t = $c.ConnectAsync("$prefix.$_", 8080) }
    }
    Start-Sleep -Milliseconds 1500
    foreach ($x in $conns) {
        $open = $x.t.IsCompleted -and -not $x.t.IsFaulted
        $x.c.Close()
        if ($open) {
            try {
                $info = Invoke-RestMethod -Uri "http://$($x.ip):8080/info" -TimeoutSec 3
                if ($info.app -eq "opentherm_esp32s3") { Write-Host "found $($info.app) $($info.version) at $($x.ip)"; return $x.ip }
            } catch {}
        }
    }
    return $null
}

$IpCache = Join-Path (Join-Path $Project ".cache") "board_ip"
function Get-BoardIp {
    if (Test-Path $IpCache) {
        $ip = (Get-Content $IpCache -Raw).Trim()
        try {
            $info = Invoke-RestMethod -Uri "http://${ip}:8080/info" -TimeoutSec 3
            if ($info.app -eq "opentherm_esp32s3") { return $ip }
        } catch {}
    }
    $ip = Find-Board
    if ($ip) { New-Item -ItemType Directory -Force (Split-Path $IpCache) | Out-Null; Set-Content $IpCache $ip }
    return $ip
}

function Invoke-RemoteCmd([string]$Line) {
    $ip = Get-BoardIp
    if (-not $ip) { Write-Host "board not found on the LAN"; return 1 }
    $hdr = @{ "X-OTA-Token" = (Get-OtaToken) }
    $before = (Invoke-WebRequest -Uri "http://${ip}:8080/log" -Headers $hdr -UseBasicParsing -TimeoutSec 5).Content
    $r = Invoke-WebRequest -Uri "http://${ip}:8080/cli" -Method Post -Headers $hdr -Body $Line -UseBasicParsing -TimeoutSec 10
    Start-Sleep -Milliseconds 1500
    $after = (Invoke-WebRequest -Uri "http://${ip}:8080/log" -Headers $hdr -UseBasicParsing -TimeoutSec 5).Content
    Write-Host "[$($r.Content)]"
    # print only what was logged after the command
    $new = if ($after.Length -gt $before.Length -and $after.StartsWith($before)) { $after.Substring($before.Length) } else { ($after -split "`n" | Select-Object -Last 30) -join "`n" }
    Write-Host ($new -replace "$([char]27)\[[0-9;]*m", "")
    return 0
}

function Invoke-LanOta([string]$Ip) {
    if (-not $Ip -or $Ip -like "COM*") { $Ip = Get-BoardIp }
    if (-not $Ip) { Write-Host "board not found on the LAN"; return 1 }
    $bin = Join-Path $IdfBuild "tuya_open_sdk.bin"
    Write-Host "uploading $bin to $Ip ..."
    $out = & curl.exe -sS --max-time 180 -H "X-OTA-Token: $(Get-OtaToken)" --data-binary "@$bin" "http://${Ip}:8080/ota"
    Write-Host $out
    if ($out -notmatch "^OK") { return 1 }
    Write-Host "rebooting into the new image; it confirms itself after 60 s online, else rolls back"
    return 0
}

Set-Location $Project
switch ($Action) {
    "clean" { tos.py clean -f }
    "build" { tos.py build }
    "flash" {
        tos.py build
        if ($LASTEXITCODE -eq 0) { exit (Invoke-Flash) }
    }
    "flash-manual" {
        if (Invoke-Esptool "no_reset" "no_reset") { Write-Host "flash OK - press RESET"; exit 0 }
        exit 1
    }
    "ota" {
        tos.py build
        if ($LASTEXITCODE -eq 0) { exit (Invoke-LanOta $Port) }
    }
    "cmd" { exit (Invoke-RemoteCmd $Port) }
    "webpass" {
        $ip = Get-BoardIp
        Write-Host "web UI: http://$(if ($ip) { $ip } else { '<board IP>' }):8080/   user: admin   password: $(Get-WebPassword)"
    }
    "rlog" {
        $ip = Get-BoardIp
        (Invoke-WebRequest -Uri "http://${ip}:8080/log" -Headers @{ "X-OTA-Token" = (Get-OtaToken) } -UseBasicParsing).Content -replace "$([char]27)\[[0-9;]*m", ""
    }
    "log" {
        $f = & $IdfPython (Join-Path $Project "tools\devlog.py") -p $Port -t $Seconds
        Get-Content $f
    }
    default { throw "unknown action: $Action" }
}
exit $LASTEXITCODE
